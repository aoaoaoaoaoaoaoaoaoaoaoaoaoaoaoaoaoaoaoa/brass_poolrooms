pub(crate) fn bake(path: &Path, [button, plate]: [Model; 2]) -> io::Result<()> {
    let sphere = sphere(9.0);
    let cylinder = cylinder(20.0, 7.0);
    let button_shadow = shadow(&button, 0.0, 82);
    let plate_shadow = shadow(&plate, 0.0, 44);
    let mut out = BufWriter::new(File::create(path)?);
    writeln!(out, "// @generated by build/optics_atlas.rs; do not edit.")?;
    writeln!(
        out,
        "pub(super) const CANDIDATE_COUNT: usize = {};",
        CANDIDATES.len()
    )?;
    writeln!(out, "pub(super) static NAMES: [&str; CANDIDATE_COUNT] = [")?;
    for candidate in CANDIDATES {
        writeln!(out, "{:?},", candidate.name)?;
    }
    writeln!(out, "];")?;
    emit(&mut out, "BUTTON_SHADOW", &button_shadow)?;
    emit(&mut out, "PLATE_SHADOW", &plate_shadow)?;
    for (index, candidate) in CANDIDATES.into_iter().enumerate() {
        emit(
            &mut out,
            &format!("CANDIDATE_{index}_BUTTON"),
            &compile_with(&button, |vertex| linear_blinn(vertex, candidate)),
        )?;
        emit(
            &mut out,
            &format!("CANDIDATE_{index}_PLATE"),
            &compile_with(&plate, |vertex| linear_blinn(vertex, candidate)),
        )?;
        emit(
            &mut out,
            &format!("CANDIDATE_{index}_SPHERE"),
            &compile_with(&sphere, |vertex| linear_blinn(vertex, candidate)),
        )?;
        emit(
            &mut out,
            &format!("CANDIDATE_{index}_CYLINDER"),
            &compile_with(&cylinder, |vertex| linear_blinn(vertex, candidate)),
        )?;
    }
    writeln!(
        out,
        "pub(super) static CELLS: [BakedOpticsCell; CANDIDATE_COUNT] = ["
    )?;
    for index in 0..CANDIDATES.len() {
        writeln!(
            out,
            "BakedOpticsCell {{ button: CANDIDATE_{index}_BUTTON, plate: CANDIDATE_{index}_PLATE, sphere: CANDIDATE_{index}_SPHERE, cylinder: CANDIDATE_{index}_CYLINDER }},"
        )?;
    }
    writeln!(out, "];")
}

fn emit(out: &mut impl Write, name: &str, mesh: &Mesh) -> io::Result<()> {
    emit_rust_as(
        out,
        name,
        mesh,
        RustReach::Module,
        RustDialect::new("BakedVertex", "BakedMesh"),
    )
}

fn linear_blinn(vertex: Vertex, candidate: Candidate) -> [u8; 4] {
    let n = vertex.normal.normalized();
    let v = (Vec3::new(0.0, 0.0, EYE_Z) - vertex.position).normalized();
    let l = Vec3::new(0.0, LIGHT_Y, LIGHT_Z);
    let h = (v + l).normalized();
    let ndl = n.dot(l).max(0.0);
    let ndv = n.dot(v).max(0.0);
    let base = candidate.charge.body.map(srgb_to_linear);
    let f0 = candidate.charge.glint.map(srgb_to_linear);
    let fresnel = f0.map(|channel| channel + (1.0 - channel) * (1.0 - ndv).powi(5));
    let lobe = specular_lobe(n, h, candidate.grain);
    let broad = n.dot(h).max(0.0).powf(7.0);
    let reflected = (n * (2.0 * ndv) - v).normalized();
    let room = room_radiance(reflected, candidate.room);
    let mut rgb = [0.0; 3];
    for channel in 0..3 {
        let body = base[channel] * (0.035 + 0.22 * ndl);
        let key = fresnel[channel] * (0.10 * broad + 0.55 * lobe) * ndl;
        let environment = fresnel[channel] * room[channel];
        rgb[channel] = filmic(1.25 * (body + key + environment));
    }
    [
        linear_to_srgb(rgb[0]),
        linear_to_srgb(rgb[1]),
        linear_to_srgb(rgb[2]),
        255,
    ]
}

fn specular_lobe(n: Vec3, h: Vec3, grain: Grain) -> f32 {
    let ndh = n.dot(h).max(0.0);
    let axis = match grain {
        Grain::Isotropic => return ndh.powf(28.0),
        Grain::Horizontal => Vec3::new(1.0, 0.0, 0.0),
        Grain::Vertical => Vec3::new(0.0, 1.0, 0.0),
    };
    let tangent = (axis - n * n.dot(axis)).normalized();
    let across = n.cross(tangent).normalized();
    let slope = (h.dot(tangent) / 0.48).powi(2) + (h.dot(across) / 0.16).powi(2);
    (-slope / ndh.powi(2).max(0.015)).exp()
}

fn room_radiance(r: Vec3, room: Room) -> [f32; 3] {
    match room {
        Room::Black => [0.0; 3],
        Room::Overhead => {
            let ceiling = smoothstep(0.02, 0.82, -r.y);
            let strip = gaussian((r.x - 0.56) / 0.14);
            let floor = smoothstep(0.10, 0.84, r.y);
            [
                0.30 * ceiling + 0.34 * strip + 0.025 * floor,
                0.22 * ceiling + 0.28 * strip + 0.020 * floor,
                0.12 * ceiling + 0.17 * strip + 0.025 * floor,
            ]
        }
        Room::Furnace => {
            let line = gaussian((r.y - 0.52) / 0.15) * gaussian((r.z - 0.24) / 0.34);
            let ember = gaussian((r.x + 0.34) / 0.30) * line;
            [
                0.62 * line + 0.22 * ember,
                0.17 * line + 0.045 * ember,
                0.018 * line,
            ]
        }
    }
}

fn srgb_to_linear(channel: u8) -> f32 {
    let encoded = f32::from(channel) / 255.0;
    if encoded <= 0.04045 {
        encoded / 12.92
    } else {
        ((encoded + 0.055) / 1.055).powf(2.4)
    }
}

fn linear_to_srgb(linear: f32) -> u8 {
    let encoded = if linear <= 0.003_130_8 {
        linear * 12.92
    } else {
        1.055 * linear.powf(1.0 / 2.4) - 0.055
    };
    (encoded * 255.0).round().clamp(0.0, 255.0) as u8
}

fn filmic(x: f32) -> f32 {
    ((x * (2.51 * x + 0.03)) / (x * (2.43 * x + 0.59) + 0.14)).clamp(0.0, 1.0)
}

fn gaussian(x: f32) -> f32 {
    (-0.5 * x * x).exp()
}

fn smoothstep(lo: f32, hi: f32, x: f32) -> f32 {
    let t = ((x - lo) / (hi - lo)).clamp(0.0, 1.0);
    t * t * (3.0 - 2.0 * t)
}

fn sphere(radius: f32) -> Model {
    const LATITUDES: usize = 10;
    const LONGITUDES: usize = 16;
    let vertex = |latitude: usize, longitude: usize| {
        let phi = -FRAC_PI_2 + latitude as f32 / LATITUDES as f32 * FRAC_PI_2 * 2.0;
        let theta = longitude as f32 / LONGITUDES as f32 * TAU;
        let normal = Vec3::new(phi.cos() * theta.cos(), phi.cos() * theta.sin(), phi.sin());
        Vertex::new(normal * radius, normal)
    };
    let mut model = Model::default();
    for latitude in 0..LATITUDES {
        for longitude in 0..LONGITUDES {
            let around = (longitude + 1) % LONGITUDES;
            model.quad([
                vertex(latitude, longitude),
                vertex(latitude, around),
                vertex(latitude + 1, around),
                vertex(latitude + 1, longitude),
            ]);
        }
    }
    model
}

fn cylinder(length: f32, radius: f32) -> Model {
    const STATIONS: usize = 24;
    let ring = |y: f32, station: usize| {
        let angle = station as f32 / STATIONS as f32 * TAU;
        let normal = Vec3::new(angle.cos(), 0.0, angle.sin());
        Vertex::new(Vec3::new(normal.x * radius, y, normal.z * radius), normal)
    };
    let mut model = Model::default();
    for station in 0..STATIONS {
        let around = (station + 1) % STATIONS;
        model.quad([
            ring(-length * 0.5, station),
            ring(-length * 0.5, around),
            ring(length * 0.5, around),
            ring(length * 0.5, station),
        ]);
    }
    model
}
