//! Build-time candidates for the feature-gated Foundry Optics Atelier.

use std::{
    f32::consts::{FRAC_PI_2, TAU},
    fs::File,
    io::{self, BufWriter, Write},
    path::Path,
};

use brass_foundry::{
    EYE_Z, LIGHT_Y, LIGHT_Z, Mesh, Model, RustDialect, RustReach, Vec3, Vertex, compile_with,
    emit_rust_as, shadow,
};

use crate::foundry_atlas::OpticsCoupons;

#[derive(Clone, Copy)]
enum Grain {
    Isotropic,
    Horizontal,
    Vertical,
}

#[derive(Clone, Copy)]
enum Room {
    Black,
    Overhead,
    Furnace,
}

#[derive(Clone, Copy)]
struct Charge {
    body: [u8; 3],
    glint: [u8; 3],
}

#[derive(Clone, Copy)]
struct Candidate {
    charge: Charge,
    grain: Grain,
    room: Room,
}

const CURRENT: Charge = Charge {
    body: [104, 86, 58],
    glint: [196, 170, 124],
};
const WARM: Charge = Charge {
    body: [119, 88, 42],
    glint: [220, 184, 104],
};
const YELLOW: Charge = Charge {
    body: [132, 99, 35],
    glint: [238, 202, 103],
};
const PALE: Charge = Charge {
    body: [153, 126, 66],
    glint: [247, 225, 156],
};

const CHARGES: [Charge; 4] = [CURRENT, WARM, YELLOW, PALE];
const GRAINS: [Grain; 3] = [Grain::Isotropic, Grain::Horizontal, Grain::Vertical];
const ROOMS: [Room; 3] = [Room::Black, Room::Overhead, Room::Furnace];
const CANDIDATE_COUNT: usize = CHARGES.len() * GRAINS.len() * ROOMS.len();

pub(crate) fn bake(path: &Path, coupons: OpticsCoupons) -> io::Result<()> {
    let sphere = sphere(9.0);
    let cylinder = cylinder(20.0, 7.0);
    let button_shadows = coupons
        .buttons
        .each_ref()
        .map(|button| shadow(button, 0.0, 82));
    let plate_shadow = shadow(&coupons.plate, 0.0, 44);
    let mut out = BufWriter::new(File::create(path)?);

    writeln!(out, "// @generated by build/optics_atlas.rs; do not edit.")?;
    writeln!(
        out,
        "pub(super) const CHARGE_COUNT: usize = {};",
        CHARGES.len()
    )?;
    writeln!(
        out,
        "pub(super) const GRAIN_COUNT: usize = {};",
        GRAINS.len()
    )?;
    writeln!(out, "pub(super) const ROOM_COUNT: usize = {};", ROOMS.len())?;
    writeln!(
        out,
        "pub(super) const CANDIDATE_COUNT: usize = {CANDIDATE_COUNT};"
    )?;

    for (gauge, shadow) in button_shadows.iter().enumerate() {
        emit(&mut out, &format!("BUTTON_SHADOW_{gauge}"), shadow)?;
    }
    writeln!(out, "pub(super) static BUTTON_SHADOWS: [BakedMesh; 3] = [")?;
    for gauge in 0..coupons.buttons.len() {
        writeln!(out, "BUTTON_SHADOW_{gauge},")?;
    }
    writeln!(out, "];")?;
    emit(&mut out, "PLATE_SHADOW", &plate_shadow)?;

    for (index, candidate) in candidates().enumerate() {
        for (gauge, button) in coupons.buttons.iter().enumerate() {
            emit(
                &mut out,
                &format!("CANDIDATE_{index}_BUTTON_{gauge}"),
                &compile_with(button, |vertex| linear_blinn(vertex, candidate, 1.0)),
            )?;
        }
        for (gauge, socket) in coupons.sockets.iter().enumerate() {
            emit(
                &mut out,
                &format!("CANDIDATE_{index}_SOCKET_{gauge}"),
                &compile_with(socket, |vertex| linear_blinn(vertex, candidate, 0.58)),
            )?;
        }
        for (name, model) in [
            ("PLATE", &coupons.plate),
            ("SPHERE", &sphere),
            ("CYLINDER", &cylinder),
            ("SCREW", &coupons.screw),
        ] {
            emit(
                &mut out,
                &format!("CANDIDATE_{index}_{name}"),
                &compile_with(model, |vertex| linear_blinn(vertex, candidate, 1.0)),
            )?;
        }
    }

    writeln!(
        out,
        "pub(super) static CELLS: [BakedOpticsCell; CANDIDATE_COUNT] = ["
    )?;
    for index in 0..CANDIDATE_COUNT {
        writeln!(
            out,
            "BakedOpticsCell {{ buttons: [CANDIDATE_{index}_BUTTON_0, CANDIDATE_{index}_BUTTON_1, CANDIDATE_{index}_BUTTON_2], sockets: [CANDIDATE_{index}_SOCKET_0, CANDIDATE_{index}_SOCKET_1, CANDIDATE_{index}_SOCKET_2], plate: CANDIDATE_{index}_PLATE, sphere: CANDIDATE_{index}_SPHERE, cylinder: CANDIDATE_{index}_CYLINDER, screw: CANDIDATE_{index}_SCREW }},"
        )?;
    }
    writeln!(out, "];")?;

    writeln!(
        out,
        "pub(super) static ETCH_PALETTES: [[BakedColor; 4]; CANDIDATE_COUNT] = ["
    )?;
    let point = Vec3::new(0.0, 0.0, 3.25);
    let normals = [
        (Vec3::new(0.0, 0.0, 1.0), 0.68),
        (Vec3::new(0.0, -0.707_106_77, 0.707_106_77), 1.12),
        (Vec3::new(0.0, 0.707_106_77, 0.707_106_77), 1.12),
        (Vec3::new(-0.707_106_77, 0.0, 0.707_106_77), 1.12),
    ];
    for candidate in candidates() {
        write!(out, "[")?;
        for (normal, exposure) in normals {
            write!(
                out,
                "{:?},",
                linear_blinn(Vertex::new(point, normal), candidate, exposure)
            )?;
        }
        writeln!(out, "],")?;
    }
    writeln!(out, "];")
}

fn candidates() -> impl Iterator<Item = Candidate> {
    CHARGES.into_iter().flat_map(|charge| {
        GRAINS.into_iter().flat_map(move |grain| {
            ROOMS.into_iter().map(move |room| Candidate {
                charge,
                grain,
                room,
            })
        })
    })
}

fn emit(out: &mut impl Write, name: &str, mesh: &Mesh) -> io::Result<()> {
    emit_rust_as(
        out,
        name,
        mesh,
        RustReach::Module,
        RustDialect::new("BakedVertex", "BakedMesh"),
    )
}

fn linear_blinn(vertex: Vertex, candidate: Candidate, exposure: f32) -> [u8; 4] {
    let n = vertex.normal.normalized();
    let v = (Vec3::new(0.0, 0.0, EYE_Z) - vertex.position).normalized();
    let l = Vec3::new(0.0, LIGHT_Y, LIGHT_Z);
    let h = (v + l).normalized();
    let ndl = n.dot(l).max(0.0);
    let ndv = n.dot(v).max(0.0);
    let base = candidate.charge.body.map(srgb_to_linear);
    let f0 = candidate.charge.glint.map(srgb_to_linear);
    let fresnel = f0.map(|channel| channel + (1.0 - channel) * (1.0 - ndv).powi(5));
    let lobe = specular_lobe(n, h, candidate.grain);
    let broad = n.dot(h).max(0.0).powf(7.0);
    let reflected = (n * (2.0 * ndv) - v).normalized();
    let room = room_radiance(reflected, candidate.room);
    let mut rgb = [0.0; 3];
    for channel in 0..3 {
        let body = base[channel] * (0.035 + 0.22 * ndl);
        let key = fresnel[channel] * (0.10 * broad + 0.55 * lobe) * ndl;
        let environment = fresnel[channel] * room[channel];
        rgb[channel] = filmic(1.25 * exposure * (body + key + environment));
    }
    [
        linear_to_srgb(rgb[0]),
        linear_to_srgb(rgb[1]),
        linear_to_srgb(rgb[2]),
        255,
    ]
}

fn specular_lobe(n: Vec3, h: Vec3, grain: Grain) -> f32 {
    let ndh = n.dot(h).max(0.0);
    let axis = match grain {
        Grain::Isotropic => return ndh.powf(28.0),
        Grain::Horizontal => Vec3::new(1.0, 0.0, 0.0),
        Grain::Vertical => Vec3::new(0.0, 1.0, 0.0),
    };
    let tangent = (axis - n * n.dot(axis)).normalized();
    let across = n.cross(tangent).normalized();
    let slope = (h.dot(tangent) / 0.48).powi(2) + (h.dot(across) / 0.16).powi(2);
    (-slope / ndh.powi(2).max(0.015)).exp()
}

fn room_radiance(r: Vec3, room: Room) -> [f32; 3] {
    match room {
        Room::Black => [0.0; 3],
        Room::Overhead => {
            let ceiling = smoothstep(0.02, 0.82, -r.y);
            let strip = gaussian((r.x - 0.56) / 0.14);
            let floor = smoothstep(0.10, 0.84, r.y);
            [
                0.30 * ceiling + 0.34 * strip + 0.025 * floor,
                0.22 * ceiling + 0.28 * strip + 0.020 * floor,
                0.12 * ceiling + 0.17 * strip + 0.025 * floor,
            ]
        }
        Room::Furnace => {
            let line = gaussian((r.y - 0.52) / 0.15) * gaussian((r.z - 0.24) / 0.34);
            let ember = gaussian((r.x + 0.34) / 0.30) * line;
            [
                0.62 * line + 0.22 * ember,
                0.17 * line + 0.045 * ember,
                0.018 * line,
            ]
        }
    }
}

fn srgb_to_linear(channel: u8) -> f32 {
    let encoded = f32::from(channel) / 255.0;
    if encoded <= 0.04045 {
        encoded / 12.92
    } else {
        ((encoded + 0.055) / 1.055).powf(2.4)
    }
}

fn linear_to_srgb(linear: f32) -> u8 {
    let encoded = if linear <= 0.003_130_8 {
        linear * 12.92
    } else {
        1.055 * linear.powf(1.0 / 2.4) - 0.055
    };
    (encoded * 255.0).round().clamp(0.0, 255.0) as u8
}

fn filmic(x: f32) -> f32 {
    ((x * (2.51 * x + 0.03)) / (x * (2.43 * x + 0.59) + 0.14)).clamp(0.0, 1.0)
}

fn gaussian(x: f32) -> f32 {
    (-0.5 * x * x).exp()
}

fn smoothstep(lo: f32, hi: f32, x: f32) -> f32 {
    let t = ((x - lo) / (hi - lo)).clamp(0.0, 1.0);
    t * t * (3.0 - 2.0 * t)
}

fn sphere(radius: f32) -> Model {
    const LATITUDES: usize = 10;
    const LONGITUDES: usize = 16;
    let vertex = |latitude: usize, longitude: usize| {
        let phi = -FRAC_PI_2 + latitude as f32 / LATITUDES as f32 * FRAC_PI_2 * 2.0;
        let theta = longitude as f32 / LONGITUDES as f32 * TAU;
        let normal = Vec3::new(phi.cos() * theta.cos(), phi.cos() * theta.sin(), phi.sin());
        Vertex::new(normal * radius, normal)
    };
    let mut model = Model::default();
    for latitude in 0..LATITUDES {
        for longitude in 0..LONGITUDES {
            let around = (longitude + 1) % LONGITUDES;
            model.quad([
                vertex(latitude, longitude),
                vertex(latitude, around),
                vertex(latitude + 1, around),
                vertex(latitude + 1, longitude),
            ]);
        }
    }
    model
}

fn cylinder(length: f32, radius: f32) -> Model {
    const STATIONS: usize = 24;
    let ring = |y: f32, station: usize| {
        let angle = station as f32 / STATIONS as f32 * TAU;
        let normal = Vec3::new(angle.cos(), 0.0, angle.sin());
        Vertex::new(Vec3::new(normal.x * radius, y, normal.z * radius), normal)
    };
    let mut model = Model::default();
    for station in 0..STATIONS {
        let around = (station + 1) % STATIONS;
        model.quad([
            ring(-length * 0.5, station),
            ring(-length * 0.5, around),
            ring(length * 0.5, around),
            ring(length * 0.5, station),
        ]);
    }
    model
}
